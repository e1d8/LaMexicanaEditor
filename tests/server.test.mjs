import test from "node:test";
import http from "node:http";
import assert from "node:assert/strict";
import { mkdtemp, mkdir, readFile, writeFile, cp, readdir, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { createEditorServer } from "../server.mjs";
const fixture = await readFile(new URL("./fixtures/menu.json", import.meta.url));

test("local API saves atomically, retains backups, validates data and prevents lost updates", async (t) => {
  const folder = await mkdtemp(path.join(tmpdir(), "mexicana-editor-test-"));
  await mkdir(path.join(folder, "assets"));
  await cp(new URL("../public/assets/allergens", import.meta.url), path.join(folder, "assets/allergens"), { recursive: true });
  const menuPath = path.join(folder, "menu.json");
  const backupDir = path.join(folder, "backups");
  await writeFile(menuPath, fixture);
  const server = createEditorServer({ menuPath, backupDir });
  await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
  const origin = `http://127.0.0.1:${server.address().port}`;
  const get = () => fetch(`${origin}/api/menu`).then((response) => response.json());
  const put = (body, headers = {}) => fetch(`${origin}/api/menu`, { method: "PUT", headers: { "Content-Type": "application/json", Origin: origin, ...headers }, body: JSON.stringify(body) });
  t.after(async () => { await new Promise((resolve) => server.close(resolve)); await rm(folder, { recursive: true, force: true }); });
  const current = await get();
  assert.equal(current.menu.sections.length, 2);
  assert.equal(current.mode, "local");
  assert.equal((await fetch(`${origin}/api/session`)).status, 404);
  assert.ok(current.icons.includes("assets/allergens/lacteo.svg"));
  const next = structuredClone(current.menu);
  next.sections[0].items.push({ name: "Nueva bebida", price: "2.50€", extra: { keep: true } });
  const results = await Promise.all([put({ version: current.version, menu: next }), put({ version: current.version, menu: next })]);
  assert.deepEqual(results.map((response) => response.status).sort(), [200, 409]);
  assert.deepEqual(JSON.parse(await readFile(menuPath)), next);
  const backups = await readdir(backupDir);
  assert.equal(backups.length, 1);
  assert.deepEqual(await readFile(path.join(backupDir, backups[0])), fixture);
  const saved = await get();
  assert.notEqual(saved.version, current.version);
  assert.equal((await put({ version: current.version, menu: next })).status, 409);
  const invalid = structuredClone(next); invalid.sections[0].items[0].price = "-2€";
  assert.equal((await put({ version: saved.version, menu: invalid })).status, 422);
  const missingIcon = structuredClone(next); missingIcon.allergens.lacteo.icon = "assets/allergens/missing.svg";
  assert.equal((await put({ version: saved.version, menu: missingIcon })).status, 422);
  assert.equal((await put({ version: saved.version, menu: next }, { Origin: "https://evil.example" })).status, 403);
  const badHostStatus = await new Promise((resolve, reject) => {
    const req = http.request(`${origin}/api/menu`, { headers: { Host: "evil.example" } }, (res) => { res.resume(); resolve(res.statusCode); });
    req.on("error", reject); req.end();
  });
  assert.equal(badHostStatus, 403);
  assert.equal((await fetch(`${origin}/api/menu`, { method: "PUT", headers: { "Content-Type": "text/plain", Origin: origin }, body: "{}" })).status, 415);
  assert.equal((await fetch(`${origin}/.git/config`)).status, 404);
  assert.equal((await fetch(`${origin}/server.mjs`)).status, 404);
  assert.deepEqual(JSON.parse(await readFile(menuPath)), next);
});
